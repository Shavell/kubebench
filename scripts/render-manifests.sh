#!/usr/bin/env bash
# Renders the plain manifests from the Helm chart, so `kubectl apply -f`
# installs the same objects as `helm install` with the variant's values.yaml,
# plus the Namespace:
#   kubernetes  deploy/kubernetes/kubebench.yaml (deploy/kubernetes/values.yaml)
#   openshift   deploy/openshift/kubebench.yaml  (deploy/openshift/values.yaml:
#               a Route, no fixed UIDs)
#
# Usage: scripts/render-manifests.sh [--variant V] [--version X.Y.Z] [--namespace NS] [--output FILE] [--check]
#   --variant V      kubernetes or openshift (default: both; one with --output)
#   --version X.Y.Z  image tag to render (default: the chart's appVersion)
#   --namespace NS   namespace to create and install into (default: kubebench)
#   --output FILE    destination of the one variant (default: kubernetes);
#                    "-" = stdout (default: deploy/<variant>/kubebench.yaml)
#   --check          do not write; exit 1 when a file differs from a fresh render
#
# Requires helm. Rendering is offline: no cluster is contacted.
set -Eeuo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
chart="$root/charts/kubebench"
namespace=kubebench
output=""
variant=""
version=""
check=0

die() { printf 'render-manifests: %s\n' "$*" >&2; exit 1; }
usage() { awk 'NR > 1 { if (!/^#/) exit; sub(/^# ?/, ""); print }' "${BASH_SOURCE[0]}"; }

while (($#)); do
  case "$1" in
    --variant) variant="${2:?--variant needs a value}"; shift 2 ;;
    --version) version="${2:?--version needs a value}"; version="${version#v}"; shift 2 ;;
    --namespace) namespace="${2:?--namespace needs a value}"; shift 2 ;;
    --output) output="${2:?--output needs a value}"; shift 2 ;;
    --check) check=1; shift ;;
    -h | --help) usage; exit 0 ;;
    *) die "unknown argument: $1 (see --help)" ;;
  esac
done

command -v helm >/dev/null 2>&1 || die "helm is required"
[[ "$namespace" =~ ^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$ ]] || die "--namespace must be a DNS label"
case "$variant" in
  kubernetes | openshift) variants=("$variant") ;;
  "") if [[ -n "$output" ]]; then variants=(kubernetes); else variants=(kubernetes openshift); fi ;;
  *) die "--variant must be kubernetes or openshift" ;;
esac

chart_field() { sed -n "s/^$1:[[:space:]]*\"\{0,1\}\([^\"]*\)\"\{0,1\}[[:space:]]*$/\1/p" "$chart/Chart.yaml"; }
chart_version="$(chart_field version)"
version="${version:-$(chart_field appVersion)}"
[[ -n "$chart_version" && -n "$version" ]] || die "cannot read version/appVersion from $chart/Chart.yaml"

# render VARIANT: the header, the Namespace and the chart's objects.
render() {
  local variant="$1" title cli
  case "$variant" in
    kubernetes) title="plain Kubernetes manifests" cli=kubectl ;;
    openshift) title="plain manifests for OpenShift" cli=oc ;;
  esac
  cat <<EOF
# KubeBench $version: $title.
# Generated by scripts/render-manifests.sh from charts/kubebench $chart_version; do not edit.
#
#   $cli apply -f kubebench.yaml
#
# Sign in as admin/admin; KubeBench asks for a new password right away.
# Guide: https://github.com/Shavell/kubebench/blob/main/deploy/$variant/README.md
---
apiVersion: v1
kind: Namespace
metadata:
  name: $namespace
  labels:
    app.kubernetes.io/name: kubebench
    app.kubernetes.io/part-of: kubebench
    pod-security.kubernetes.io/enforce: restricted
    pod-security.kubernetes.io/warn: restricted
    pod-security.kubernetes.io/audit: restricted
EOF
  helm template kubebench "$chart" \
    --namespace "$namespace" \
    --values "$root/deploy/$variant/values.yaml" \
    --set-string image.tag="$version"
}

for variant in "${variants[@]}"; do
  file="${output:-$root/deploy/$variant/kubebench.yaml}"
  rendered="$(render "$variant")"

  if ((check)); then
    if [[ "$file" == "-" ]] || ! diff -u "$file" <(printf '%s\n' "$rendered") >&2; then
      die "$file is stale; run scripts/render-manifests.sh (or make manifests)"
    fi
  elif [[ "$file" == "-" ]]; then
    printf '%s\n' "$rendered"
  else
    mkdir -p "$(dirname "$file")"
    printf '%s\n' "$rendered" >"$file"
    printf 'render-manifests: wrote %s\n' "${file#"$root"/}" >&2
  fi
done
