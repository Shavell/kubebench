#!/usr/bin/env bash
# Renders the plain Kubernetes manifests (deploy/kubernetes/kubebench.yaml)
# from the Helm chart, so `kubectl apply -f` installs the same objects as
# `helm install` with deploy/kubernetes/values.yaml, plus the Namespace.
#
# Usage: scripts/render-manifests.sh [--version X.Y.Z] [--namespace NS] [--output FILE] [--check]
#   --version X.Y.Z  image tag to render (default: the chart's appVersion)
#   --namespace NS   namespace to create and install into (default: kubebench)
#   --output FILE    destination (default: deploy/kubernetes/kubebench.yaml; "-" = stdout)
#   --check          do not write; exit 1 when FILE differs from a fresh render
#
# Requires helm. Rendering is offline: no cluster is contacted.
set -Eeuo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
chart="$root/charts/kubebench"
namespace=kubebench
output="$root/deploy/kubernetes/kubebench.yaml"
version=""
check=0

die() { printf 'render-manifests: %s\n' "$*" >&2; exit 1; }
usage() { awk 'NR > 1 { if (!/^#/) exit; sub(/^# ?/, ""); print }' "${BASH_SOURCE[0]}"; }

while (($#)); do
  case "$1" in
    --version) version="${2:?--version needs a value}"; version="${version#v}"; shift 2 ;;
    --namespace) namespace="${2:?--namespace needs a value}"; shift 2 ;;
    --output) output="${2:?--output needs a value}"; shift 2 ;;
    --check) check=1; shift ;;
    -h | --help) usage; exit 0 ;;
    *) die "unknown argument: $1 (see --help)" ;;
  esac
done

command -v helm >/dev/null 2>&1 || die "helm is required"
[[ "$namespace" =~ ^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$ ]] || die "--namespace must be a DNS label"

chart_field() { sed -n "s/^$1:[[:space:]]*\"\{0,1\}\([^\"]*\)\"\{0,1\}[[:space:]]*$/\1/p" "$chart/Chart.yaml"; }
chart_version="$(chart_field version)"
version="${version:-$(chart_field appVersion)}"
[[ -n "$chart_version" && -n "$version" ]] || die "cannot read version/appVersion from $chart/Chart.yaml"

render() {
  cat <<EOF
# KubeBench $version: plain Kubernetes manifests.
# Generated by scripts/render-manifests.sh from charts/kubebench $chart_version; do not edit.
#
#   kubectl apply -f kubebench.yaml
#
# Sign in as admin/admin; KubeBench asks for a new password right away.
# Guide: https://github.com/Shavell/kubebench/blob/main/deploy/kubernetes/README.md
---
apiVersion: v1
kind: Namespace
metadata:
  name: $namespace
  labels:
    app.kubernetes.io/name: kubebench
    app.kubernetes.io/part-of: kubebench
    pod-security.kubernetes.io/enforce: restricted
    pod-security.kubernetes.io/warn: restricted
    pod-security.kubernetes.io/audit: restricted
EOF
  helm template kubebench "$chart" \
    --namespace "$namespace" \
    --values "$root/deploy/kubernetes/values.yaml" \
    --set-string image.tag="$version"
}

rendered="$(render)"

if ((check)); then
  if [[ "$output" == "-" ]] || ! diff -u "$output" <(printf '%s\n' "$rendered") >&2; then
    die "$output is stale; run scripts/render-manifests.sh (or make manifests)"
  fi
  exit 0
fi

if [[ "$output" == "-" ]]; then
  printf '%s\n' "$rendered"
else
  mkdir -p "$(dirname "$output")"
  printf '%s\n' "$rendered" >"$output"
  printf 'render-manifests: wrote %s\n' "${output#"$root"/}" >&2
fi
